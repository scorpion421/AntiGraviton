def _replace_regex_in_file(path: Path, replacements: list) -> None:
    if not path.exists():
        return
    original = path.read_text(encoding="utf-8")
    updated = original
    for pattern, repl in replacements:
        updated = re.sub(pattern, lambda _m, r=repl: r, updated)
    if updated != original:
        path.write_text(updated, encoding="utf-8")


def sync_project_versions(repo_root: Path, suite_ver: str, eng_ver: str) -> None:
    """Synchronizes suite_ver and eng_ver from skillsdb/config.py across all project manifests, installers, and docs."""
    import json as _json
    import sqlite3 as _sqlite3
    from datetime import datetime, timezone

    version_file = repo_root / "VERSION"
    if not version_file.exists() or version_file.read_text(encoding="utf-8").strip() != suite_ver:
        version_file.write_text(f"{suite_ver}\n", encoding="utf-8")

    plugin_json_path = repo_root / "plugin" / "plugin.json"
    if plugin_json_path.exists():
        p_data = _json.loads(plugin_json_path.read_text(encoding="utf-8"))
        if p_data.get("version") != eng_ver:
            p_data["version"] = eng_ver
            plugin_json_path.write_text(_json.dumps(p_data, indent=2) + "\n", encoding="utf-8")

    _replace_regex_in_file(
        repo_root / "plugin" / "README.md",
        [
            (
                r"AntiGraviton `v[0-9.]+` \(`SkillsDB v[0-9.]+`\)",
                f"AntiGraviton `v{suite_ver}` (`SkillsDB v{eng_ver}`)",
            ),
        ],
    )

    _replace_regex_in_file(
        repo_root / "README.md",
        [
            (r"# AntiGraviton complete suite \(`v[0-9.]+`\)", f"# AntiGraviton complete suite (`v{suite_ver}`)"),
            (r"\*\*SkillsDB \(`v[0-9.]+`\)\*\*", f"**SkillsDB (`v{eng_ver}`)**"),
            (r"\*\*SkillsDB context and memory engine \(`v[0-9.]+`\)\*\*", f"**SkillsDB context and memory engine (`v{eng_ver}`)**"),
            (r"\| AntiGraviton suite \(`v[0-9.]+`\) \|", f"| AntiGraviton suite (`v{suite_ver}`) |"),
            (r"# SemVer 2\.0\.0 suite release version \([0-9.]+\)", f"# SemVer 2.0.0 suite release version ({suite_ver})"),
            (r"# Modular Python package source \(v[0-9.]+\)", f"# Modular Python package source (v{eng_ver})"),
        ],
    )

    _replace_regex_in_file(
        repo_root / "install-antigraviton.ps1",
        [
            (r"AntiGraviton Complete Suite \(v[0-9.]+\)", f"AntiGraviton Complete Suite (v{suite_ver})"),
            (r"SkillsDB Context & Memory Engine \(v[0-9.]+\)", f"SkillsDB Context & Memory Engine (v{eng_ver})"),
            (r'else \{ "[0-9.]+" \}', f'else {{ "{suite_ver}" }}'),
            (r"Deploying SkillsDB Engine \(v[0-9.]+\)", f"Deploying SkillsDB Engine (v{eng_ver})"),
            (r"SkillsDB Engine \(v[0-9.]+\):", f"SkillsDB Engine (v{eng_ver}):"),
        ],
    )

    _replace_regex_in_file(
        repo_root / "install_antigraviton.py",
        [
            (r"AntiGraviton Complete Suite \(v[0-9.]+\)", f"AntiGraviton Complete Suite (v{suite_ver})"),
            (r"SkillsDB Context & Memory Engine \(v[0-9.]+\)", f"SkillsDB Context & Memory Engine (v{eng_ver})"),
            (r'else "[0-9.]+"', f'else "{suite_ver}"'),
            (r"Deploying SkillsDB Engine \(v[0-9.]+\)", f"Deploying SkillsDB Engine (v{eng_ver})"),
        ],
    )

    _replace_regex_in_file(
        repo_root / ".agents" / "skills" / "install-antigraviton" / "SKILL.md",
        [
            (r"\(SkillsDB v[0-9.]+ \+", f"(SkillsDB v{eng_ver} +"),
            (r"\*\*SkillsDB Context & Memory Engine \(`v[0-9.]+`\)\*\*", f"**SkillsDB Context & Memory Engine (`v{eng_ver}`)**"),
        ],
    )

    db_file = repo_root / "database" / "customizations.db"
    if db_file.exists():
        try:
            conn = _sqlite3.connect(str(db_file), timeout=10.0)
            try:
                cur = conn.cursor()
                row = cur.execute("SELECT value FROM runtime_config WHERE key = 'schema_version';").fetchone()
                if row and row[0] != eng_ver:
                    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
                    cur.execute(
                        "UPDATE runtime_config SET value = ?, updated_at = ? WHERE key = 'schema_version';",
                        (eng_ver, now_str),
                    )
                    conn.commit()
            finally:
                conn.close()
        except Exception:
            pass


def bundle():
    repo_root = Path(__file__).parent.resolve()
    pkg_dir = repo_root / "skillsdb"
    target_file = repo_root / "database" / "db_manager.py"

    print("=" * 60)
    print("SkillsDB Bundler: Compiling package into standalone db_manager.py")
    print(f"Source Package: {pkg_dir}")
    print(f"Target Output:  {target_file}")
    print("=" * 60)

    if not pkg_dir.exists():
        print(f"Error: {pkg_dir} does not exist.")
        sys.exit(1)

    cfg_text = (pkg_dir / "config.py").read_text(encoding="utf-8")
    m_ver = re.search(r'__version__\s*=\s*"([^"]+)"', cfg_text)
    m_sver = re.search(r'__suite_version__\s*=\s*"([^"]+)"', cfg_text)
    eng_ver = m_ver.group(1) if m_ver else "3.7.9"
    suite_ver = m_sver.group(1) if m_sver else "1.4.9"

    header_str = re.sub(r"Version:\s*[0-9.]+", f"Version: {eng_ver}", HEADER.strip())
    bundled_chunks = [header_str]

    sync_project_versions(repo_root, suite_ver, eng_ver)

    for rel_path in MODULE_ORDER:
        module_path = pkg_dir / rel_path
        if not module_path.exists():
            print(f"Error: Required module file {module_path} not found.")
            sys.exit(1)

        print(f"  * Bundling: skillsdb/{rel_path}")
        content = module_path.read_text(encoding="utf-8")
        lines = content.splitlines()

        filtered_lines = []
        in_module_docstring = False
        docstring_done = False
        in_multiline_skip = False
        in_win_reconfig = False

        for idx, line in enumerate(lines):
            stripped = line.strip()

            # Handle multiline import skips
            if in_multiline_skip:
                if ")" in stripped:
                    in_multiline_skip = False
                continue

            # Strip leading module docstrings
            if not docstring_done:
                if stripped.startswith('"""') or stripped.startswith("'''"):
                    if (stripped.count('"""') >= 2 or stripped.count("'''") >= 2) and len(stripped) > 3:
                        docstring_done = True
                        continue
                    in_module_docstring = not in_module_docstring
                    if not in_module_docstring:
                        docstring_done = True
                    continue
                if in_module_docstring:
                    continue
                if not stripped:
                    continue
                docstring_done = True

            # Skip package-relative imports (from . or from ..)
            if line == stripped and re.match(r"^from\s+\.+[A-Za-z0-9_.]*\s+import\b", stripped):
                if "(" in stripped and ")" not in stripped:
                    in_multiline_skip = True
                continue

            # Skip top-level standard library imports already in header
            if line == stripped and re.match(r"^(import|from)\s+(os|io|sys|re|json|time|stat|uuid|queue|random|atexit|base64|shutil|sqlite3|tempfile|argparse|threading|subprocess|contextlib|importlib|urllib|concurrent|pathlib|datetime|typing)\b", stripped):
                if "(" in stripped and ")" not in stripped:
                    in_multiline_skip = True
                continue

            # Skip top-level win32 reconfigure in config.py
            if rel_path == "config.py":
                if stripped == 'if sys.platform == "win32":':
                    in_win_reconfig = True
                    continue
                if in_win_reconfig:
                    if stripped.startswith("__version__") or stripped.startswith("#"):
                        in_win_reconfig = False
                    else:
                        continue

            # Skip trailing 'if __name__ == "__main__": main()' inside individual files
            if stripped == 'if __name__ == "__main__":':
                continue
            if stripped == "main()" and idx > 0 and 'if __name__ == "__main__":' in lines[idx - 1]:
                continue

            filtered_lines.append(line)

        mod_name = rel_path.replace("/", ".").replace("\\", ".").replace(".py", "")
        chunk_header = f"\n# =====================================================================\n# SECTION: skillsdb.{mod_name}\n# =====================================================================\n"
        bundled_chunks.append(chunk_header + "\n".join(filtered_lines).strip())

    # Add final entrypoint execution
    entrypoint = """
# =====================================================================
# Standalone CLI Entrypoint
# =====================================================================
if __name__ == "__main__":
    main()
"""
    bundled_chunks.append(entrypoint.strip())

    final_content = "\n\n".join(bundled_chunks) + "\n"

    # Syntax validation before saving
    try:
        compile(final_content, "db_manager.py", "exec")
        print("  * Syntax validation: PASSED")
    except SyntaxError as e:
        print(f"  * Syntax validation FAILED at line {e.lineno}: {e.msg}")
        sys.exit(1)

    target_file.parent.mkdir(parents=True, exist_ok=True)
    target_file.write_text(final_content, encoding="utf-8")
    print(f"\n[OK] Successfully compiled {len(MODULE_ORDER)} modules into:\n{target_file}")
    print(f"Total lines: {len(final_content.splitlines())} lines (~{len(final_content) // 1024} KB)")


if __name__ == "__main__":
    bundle()
