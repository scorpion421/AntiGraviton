    try:
        conn.execute("PRAGMA incremental_vacuum;")
        conn.commit()
    except Exception:
        pass

    if not silent:
        print("\n=== SESSION AUTO-COMPACTION COMPLETED ===")
        print(f"  Summary:          {snap_summary}")
